void read_adc(void *p){
	for(;;){
 		//HAL_ADC_Start_IT(&hadc1);
 		HAL_ADC_Start_DMA(&hadc1, (uint32_t*)&Temp_DMA_BUFFER, 2);
		vTaskDelay(1000/portTICK_RATE_MS);
	}
}
void temp_write(void *p){
	xDataAdc xDataToConvert;
	float xTemperature = 0;
	int xTempMsg[2] = {0,0};
	/*Debido a que el hardware es capaz de hacerlo, se utiliza tipo de dato
	 * float para calcular los datos*/
	float xVrefInt = 0;
	float xVMeasured = 0;
	BaseType_t xStatus;
	char uart_buffer[30];
	for(;;){
		xStatus = xQueueReceive(xAdcTempHandle, &xDataToConvert, 100/portTICK_RATE_MS);
		if(xStatus==pdPASS){
			//Vref va desde 1.8 hasta 3.6 ---> 4096===3.6V
			xVrefInt = (float)(VREFINT*ADCMAX)/((float)xDataToConvert.VrefVal);
			xVMeasured= (xVrefInt*((float)xDataToConvert.TempVal))/ADCMAX;
			xTemperature = (float)(((xVMeasured-V25C)/AVGSLP+25));
			xTempMsg[0]	=	(int)xTemperature;
			xTempMsg[1]	=	(int)((xTemperature-xTempMsg[0])*100);
			snprintf(uart_buffer, sizeof(uart_buffer), "Temp: %d.%02d C\r\n",xTempMsg[0],xTempMsg[1]);
			HAL_UART_Transmit(&huart1, (uint8_t *)uart_buffer, strlen(uart_buffer), HAL_MAX_DELAY);
			/*Todos los calculos fueron realizados basándose en el manual de referencia RM0383 para STM32F411xC/E*/
			vTaskDelay(1000/portTICK_RATE_MS);
		}
	}
}
uint8_t uint16_to_ascii(uint16_t num, char* buffer, int len) {
    uint8_t i = 0;
    uint8_t length = 0;
    char temp[5];
    // Caso 0
    if (num == 0) {
        buffer[0] = '0';
        buffer[1] = '\0';
        return 1;
    }
    while (num > 0) {
        temp[i++] = (num % 10) + '0';
        num /= 10;
    }
    length = i;
    while (i > 0) {
        buffer[length - i] = temp[i-1];
        i--;
    }
    buffer[length] = '\0';
    return length;
}

